#!/usr/bin/env python3
"""Every store and launcher icon from one mark + one background.

    python3 icons.py --mark branding/mark.svg --bg "#FF7A2E,#EE4D12"
    python3 icons.py --mark mark.png --bg "#111827" --mono mark_mono.svg --out store-assets/out/icons
    python3 icons.py --icon branding/icon_1024.png          # store icons only (no adaptive layers)

--mark is the artwork alone on a transparent canvas (SVG or a large PNG).
--bg is one colour or two (a top-left -> bottom-right gradient).

Writes <out>/
  play/icon-512.png                       Play Console listing icon (full square; Play masks it)
  appstore/icon-1024.png                  App Store icon (opaque, square; Apple masks it)
  appstore/AppIcon.appiconset/            Xcode asset: light + dark + tinted (iOS 18+)
  icon-composer/                          background.png + foreground.png to layer in Icon Composer (Xcode 26+)
  android/res/...                         adaptive icon (foreground, background, monochrome), legacy + round PNGs
  preview.png                             the icon under each platform mask and at small sizes: look at it
  manifest.json                           for check.py

Add --android-res app/src/main/res and/or --ios-appiconset ios/Runner/Assets.xcassets/AppIcon.appiconset
to also write straight into the project (overwrites the launcher icon files there).
"""

from __future__ import annotations

import argparse
import json
import math
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import sa  # noqa: E402,F401  (checks Python and Pillow first)
from PIL import Image, ImageDraw, ImageOps  # noqa: E402

from sa import core  # noqa: E402
from sa.project import load_specs, open_image  # noqa: E402

M = 1024  # master canvas
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
SAFE_R = 33 / 108  # adaptive safe zone radius, as a fraction of the canvas


def gradient(colors, size=M) -> Image.Image:
    a = core.hex_rgb(colors[0])
    b = core.hex_rgb(colors[-1])
    if a == b:
        return Image.new("RGBA", (size, size), a + (255,))
    g = Image.new("L", (256, 256))  # top-left (a) -> bottom-right (b)
    g.putdata([round((x + y) * 255 / 510) for y in range(256) for x in range(256)])
    g = g.resize((size, size), Image.BICUBIC)
    img = Image.new("RGBA", (size, size), a + (255,))
    img.paste(b + (255,), (0, 0), g)
    return img


def trimmed(img: Image.Image) -> Image.Image:
    box = img.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox()
    if not box:
        raise SystemExit("the mark is fully transparent")
    return img.crop(box)


def placed(mark: Image.Image, frac: float, size=M) -> Image.Image:
    """Mark scaled so its longer side is frac * size, centred on its inked box."""
    k = frac * size / max(mark.size)
    m = mark.resize((max(1, round(mark.width * k)), max(1, round(mark.height * k))), Image.LANCZOS)
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    out.alpha_composite(m, ((size - m.width) // 2, (size - m.height) // 2))
    return out


def reach(layer: Image.Image) -> float:
    """Farthest inked pixel from the centre, as a fraction of the canvas."""
    a = layer.getchannel("A").resize((256, 256), Image.BILINEAR)
    px = a.load()
    best = 0.0
    for y in range(256):
        for x in range(256):
            if px[x, y] > 24:
                best = max(best, math.hypot(x + 0.5 - 128, y + 0.5 - 128))
    return best / 256


def flat(color, alpha_from: Image.Image) -> Image.Image:
    out = Image.new("RGBA", alpha_from.size, tuple(color) + (0,))
    out.putalpha(alpha_from.getchannel("A"))
    return out


def save_png(img: Image.Image, path: Path, opaque=False) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    (img.convert("RGB") if opaque else img).save(path, optimize=True)
    return path


ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by store-assets icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/{name}_background" />
    <foreground android:drawable="@mipmap/{name}_foreground" />
    <monochrome android:drawable="@mipmap/{name}_monochrome" />
</adaptive-icon>
"""


def appiconset(dest: Path, light: Image.Image, dark: Image.Image | None, tinted: Image.Image | None) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    images = [{"filename": "icon-1024.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"}]
    save_png(light, dest / "icon-1024.png", opaque=True)
    if dark is not None:
        save_png(dark, dest / "icon-1024-dark.png")
        images.append({"appearances": [{"appearance": "luminosity", "value": "dark"}], "filename": "icon-1024-dark.png",
                       "idiom": "universal", "platform": "ios", "size": "1024x1024"})
    if tinted is not None:
        save_png(tinted, dest / "icon-1024-tinted.png", opaque=True)
        images.append({"appearances": [{"appearance": "luminosity", "value": "tinted"}],
                       "filename": "icon-1024-tinted.png", "idiom": "universal", "platform": "ios",
                       "size": "1024x1024"})
    (dest / "Contents.json").write_text(json.dumps({"images": images, "info": {"author": "xcode", "version": 1}},
                                                   indent=2) + "\n", encoding="utf-8")


def _ic_color(c) -> str:
    r, g, b = core.hex_rgb(c)
    return f"extended-srgb:{r / 255:.5f},{g / 255:.5f},{b / 255:.5f},1.00000"


def icon_composer(dest: Path, mark_layer: Image.Image, colors) -> None:
    """A starter Icon Composer bundle (Xcode 26+ Liquid Glass): one glass group holding the mark.

    Modelled on bundles Icon Composer writes. Open it in Icon Composer to tune
    glass, shadow and the dark/tinted looks before shipping.
    """
    (dest / "Assets").mkdir(parents=True, exist_ok=True)
    save_png(mark_layer, dest / "Assets" / "Mark.png")
    fill = {"solid": _ic_color(colors[0])} if len(colors) == 1 or colors[0] == colors[-1] \
        else {"automatic-gradient": _ic_color(colors[0])}
    doc = {
        "fill-specializations": [{"value": fill}, {"appearance": "dark", "value": "automatic"}],
        "groups": [{
            "blur-material": 0.5,
            "layers": [{
                "fill-specializations": [
                    {"appearance": "dark", "value": {"solid": "extended-gray:1.00000,1.00000"}},
                    {"appearance": "tinted", "value": {"solid": "extended-gray:1.00000,1.00000"}},
                ],
                "glass": True,
                "image-name": "Mark.png",
                "name": "Mark",
                "position": {"scale": 1, "translation-in-points": [0, 0]},
            }],
            "lighting": "individual",
            "shadow": {"kind": "neutral", "opacity": 0.5},
            "specular": True,
            "translucency": {"enabled": True, "value": 0.5},
        }],
        "supported-platforms": {"squares": "shared"},
    }
    (dest / "icon.json").write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")


def preview(out: Path, full: Image.Image, dark, tinted_src, fg, bg, mono, accent) -> Path:
    """Masks and sizes side by side, labelled, on a mid grey."""
    tiles = []

    def tile(img, mask, label, size=180):
        t = img.resize((size, size), Image.LANCZOS)
        canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        canvas.paste(t, (0, 0), mask.resize((size, size), Image.LANCZOS))
        tiles.append((canvas, label))

    sq = core.superellipse_mask(M)
    tile(full, sq, "iOS")
    if dark is not None:
        dk = Image.new("RGBA", (M, M), (24, 24, 28, 255))
        dk.alpha_composite(dark)
        tile(dk, sq, "iOS dark")
    if tinted_src is not None:
        tint = core.mix(accent, (255, 255, 255), 0.25)
        g = ImageOps.grayscale(tinted_src.convert("RGB"))
        col = Image.merge("RGB", [g.point(lambda v, c=c: v * c // 255) for c in tint]).convert("RGBA")
        tile(col, sq, "iOS tinted")
    if fg is not None:
        layered = bg.copy()
        layered.alpha_composite(fg)
        # Launchers show the inner 72dp of the 108dp layers.
        inner = layered.crop((M * 18 // 108, M * 18 // 108, M * 90 // 108, M * 90 // 108)).resize((M, M))
        tile(inner, core.ellipse_mask((M, M)), "Android circle")
        tile(inner, core.superellipse_mask(M, 3.2), "Android squircle")
        tile(inner, core.rr_mask((M, M), M * 0.2), "Android rounded")
        if mono is not None:
            mono_inner = mono.crop((M * 18 // 108, M * 18 // 108, M * 90 // 108, M * 90 // 108)).resize((M, M))
            themed = Image.new("RGBA", (M, M), core.mix(accent, (255, 255, 255), 0.82) + (255,))
            themed.alpha_composite(flat(core.mix(accent, (0, 0, 0), 0.6), mono_inner))
            tile(themed, core.ellipse_mask((M, M)), "Android themed")
        # safe-zone overlay
        guide = inner.copy()
        d = ImageDraw.Draw(guide)
        r = SAFE_R * M * 108 / 72
        d.ellipse((M / 2 - r, M / 2 - r, M / 2 + r, M / 2 + r), outline=(255, 0, 80, 255), width=10)
        tile(guide, Image.new("L", (M, M), 255), "safe zone (66dp)")
    tile(full, core.rr_mask((M, M), M * 0.3), "Play listing")
    small = [(full, sq, s) for s in (60, 40, 29)]

    pad, label_h = 28, 40
    W = pad + sum(t.width + pad for t, _ in tiles)
    H = pad + 180 + label_h + pad + 60 + pad
    sheet = Image.new("RGBA", (max(W, 600), H), (150, 150, 156, 255))
    d = ImageDraw.Draw(sheet)
    f = core.Fonts({}, out).get("body", 18)
    x = pad
    for t, label in tiles:
        sheet.alpha_composite(t, (x, pad))
        d.text((x + t.width / 2, pad + 180 + 10), label, font=f, fill=(20, 20, 24), anchor="ma")
        x += t.width + pad
    x = pad
    y = pad + 180 + label_h + pad
    for img, mask, s in small:
        tile_img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
        tile_img.paste(img.resize((s, s), Image.LANCZOS), (0, 0), mask.resize((s, s), Image.LANCZOS))
        sheet.alpha_composite(tile_img, (x, y + (60 - s)))
        d.text((x + s + 8, y + 60 - 22), f"{s}px", font=f, fill=(20, 20, 24))
        x += s + 80
    p = out / "preview.png"
    sheet.convert("RGB").save(p)
    return p


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--mark", help="artwork on a transparent canvas (svg/png)")
    src.add_argument("--icon", help="a finished full-bleed square icon (svg/png); store icons only")
    ap.add_argument("--bg", help="background: '#RRGGBB' or '#top,#bottom' (with --mark)")
    ap.add_argument("--mono", help="monochrome mark for Android themed / iOS tinted (default: the mark's shape)")
    ap.add_argument("--dark-mark", help="mark to use on the iOS dark icon (default: the mark)")
    ap.add_argument("--mark-size", type=float, default=0.60, help="mark's longer side on full icons (fraction)")
    ap.add_argument("--adaptive-size", type=float, default=0.46,
                    help="mark's longer side on the 108dp adaptive canvas (fraction); auto-shrunk to the safe zone")
    ap.add_argument("--accent", help="tint for previews (default: the background colour)")
    ap.add_argument("--name", default="ic_launcher")
    ap.add_argument("--out", default="store-assets/out/icons")
    ap.add_argument("--android-res", help="also write the Android launcher icons into this res/ dir")
    ap.add_argument("--ios-appiconset", help="also write the AppIcon.appiconset contents into this dir")
    args = ap.parse_args(argv)

    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    specs = load_specs()
    files = []

    if args.icon:
        full = open_image(Path(args.icon), M)
        if full.getchannel("A").getextrema()[0] < 250:
            core.warn("--icon has transparent pixels; the App Store copy is flattened onto black. Prefer a full-bleed "
                      "square, or use --mark with --bg.")
        mark = fg = bg = mono = dark = tinted = None
        accent = core.hex_rgb(args.accent) if args.accent else (128, 128, 128)
        flat_full = Image.new("RGBA", (M, M), (0, 0, 0, 255))
        flat_full.alpha_composite(full)
        full = flat_full
    else:
        if not args.bg:
            raise SystemExit("--mark needs --bg")
        colors = [c.strip() for c in args.bg.split(",")]
        accent = core.hex_rgb(args.accent or colors[0])
        mark = trimmed(open_image(Path(args.mark), 2048))
        bg = gradient(colors)
        full = bg.copy()
        full.alpha_composite(placed(mark, args.mark_size))

        # adaptive foreground: shrink until it sits inside the 66dp safe circle
        frac = args.adaptive_size
        fg = placed(mark, frac)
        r = reach(fg)
        if r > SAFE_R * 0.97:
            frac *= SAFE_R * 0.97 / r
            fg = placed(mark, frac)
            core.warn(f"adaptive mark shrunk to {frac:.2f} of the canvas to stay inside the 66dp safe zone")
        if frac * 108 < 44:
            core.warn(f"adaptive mark is {frac * 108:.0f}dp; Android asks for at least 48dp. A wide mark may need "
                      f"a more compact version for launchers.")
        mono_src = trimmed(open_image(Path(args.mono), 2048)) if args.mono else mark
        mono = flat((0, 0, 0), placed(mono_src, frac))
        dark_src = trimmed(open_image(Path(args.dark_mark), 2048)) if args.dark_mark else mark
        dark = placed(dark_src, args.mark_size)  # transparent: iOS draws its dark backdrop
        tinted = Image.new("RGBA", (M, M), (0, 0, 0, 255))
        tinted.alpha_composite(flat((255, 255, 255), placed(mono_src, args.mark_size)))

    # store icons
    files.append(("play-icon", save_png(full.resize((512, 512), Image.LANCZOS), out / "play/icon-512.png",
                                        opaque=True)))
    files.append(("ios-icon", save_png(full, out / "appstore/icon-1024.png", opaque=True)))
    appiconset(out / "appstore/AppIcon.appiconset", full, dark, tinted)
    if args.ios_appiconset:
        appiconset(Path(args.ios_appiconset), full, dark, tinted)
        print("wrote", args.ios_appiconset)

    if mark is not None:
        save_png(bg, out / "icon-composer/background.png", opaque=True)
        save_png(placed(mark, args.mark_size), out / "icon-composer/foreground.png")
        icon_composer(out / "icon-composer/AppIcon.icon", placed(mark, args.mark_size), colors)

        res = out / "android/res"
        legacy_bg = Image.new("RGBA", (M, M), (0, 0, 0, 0))
        inset = round(M * 64 / 1024)
        legacy_bg.paste(bg.resize((M - 2 * inset, M - 2 * inset)), (inset, inset),
                        core.rr_mask((M - 2 * inset, M - 2 * inset), M * 0.2))
        legacy = legacy_bg.copy()
        legacy.alpha_composite(placed(mark, args.mark_size * 0.82))
        round_icon = Image.new("RGBA", (M, M), (0, 0, 0, 0))
        round_icon.paste(full.resize((M - 2 * inset, M - 2 * inset)), (inset, inset),
                         core.ellipse_mask((M - 2 * inset, M - 2 * inset)))
        for dens, mult in DENSITIES.items():
            d = res / f"mipmap-{dens}"
            px = round(108 * mult)
            save_png(fg.resize((px, px), Image.LANCZOS), d / f"{args.name}_foreground.png")
            save_png(bg.resize((px, px), Image.LANCZOS), d / f"{args.name}_background.png", opaque=True)
            save_png(mono.resize((px, px), Image.LANCZOS), d / f"{args.name}_monochrome.png")
            lp = round(48 * mult)
            save_png(legacy.resize((lp, lp), Image.LANCZOS), d / f"{args.name}.png")
            save_png(round_icon.resize((lp, lp), Image.LANCZOS), d / f"{args.name}_round.png")
        anydpi = res / "mipmap-anydpi-v26"
        anydpi.mkdir(parents=True, exist_ok=True)
        for n in (args.name, f"{args.name}_round"):
            (anydpi / f"{n}.xml").write_text(ADAPTIVE_XML.format(name=args.name), encoding="utf-8")
        if args.android_res:
            dest = Path(args.android_res)
            for p in res.rglob("*"):
                if p.is_file():
                    t = dest / p.relative_to(res)
                    t.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(p, t)
            print("wrote launcher icons into", dest)
            core.warn("check AndroidManifest.xml: android:icon=\"@mipmap/" + args.name + "\" and android:roundIcon="
                      "\"@mipmap/" + args.name + "_round\"; delete any drawable/" + args.name + "_*.xml that would "
                      "shadow the new mipmaps")

    p = preview(out, full, dark, tinted, fg, bg, mono, accent)
    (out / "manifest.json").write_text(json.dumps(
        {"files": [{"target": t, "path": str(f.relative_to(out)), "kind": "icon"} for t, f in files]}, indent=2) + "\n", encoding="utf-8")
    for t, f in files:
        print("wrote", f.relative_to(out), f"({specs['icons'][t]['size'][0]}px)")
    print("wrote appstore/AppIcon.appiconset/, android/res/, icon-composer/" if mark is not None
          else "wrote appstore/AppIcon.appiconset/")
    print("preview:", p)
    core.report_warnings()
    return 0


if __name__ == "__main__":
    sys.exit(main())
